export const RTL_LANGUAGE_CODES = new Set(['ar', 'ur', 'fa', 'he']);

export function isRtlLanguage(code?: string, sampleText?: string): boolean {
  if (code && RTL_LANGUAGE_CODES.has(code.toLowerCase().slice(0, 2))) {
    return true;
  }
  if (sampleText) {
    // Check for Arabic / Urdu / Hebrew Unicode script ranges
    return /[\u0600-\u06FF\u0750-\u077F\u08A0-\u08FF\uFB50-\uFDFF\uFE70-\uFEFF\u0590-\u05FF]/.test(sampleText);
  }
  return false;
}

